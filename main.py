class Canvas:
    """A tiny RGB framebuffer with just enough drawing for a page."""

    def __init__(self, width, height, colour):
        self.width = width
        self.height = height
        self.pixels = bytearray(colour * (width * height))

    def set(self, x, y, colour):
        if 0 <= x < self.width and 0 <= y < self.height:
            off = (y * self.width + x) * 3
            self.pixels[off:off + 3] = bytes(colour)

    def rect(self, x, y, w, h, colour):
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                self.set(xx, yy, colour)

    def frame(self, x, y, w, h, colour, thick=3):
        self.rect(x, y, w, thick, colour)
        self.rect(x, y + h - thick, w, thick, colour)
        self.rect(x, y, thick, h, colour)
        self.rect(x + w - thick, y, thick, h, colour)

    def line(self, x0, y0, x1, y1, colour, thick=2):
        steps = max(abs(x1 - x0), abs(y1 - y0), 1)
        for i in range(steps + 1):
            x = x0 + (x1 - x0) * i // steps
            y = y0 + (y1 - y0) * i // steps
            self.rect(x - thick // 2, y - thick // 2, thick, thick, colour)

    def disc(self, cx, cy, r, colour):
        for yy in range(cy - r, cy + r + 1):
            for xx in range(cx - r, cx + r + 1):
                if (xx - cx) ** 2 + (yy - cy) ** 2 <= r * r:
                    self.set(xx, yy, colour)

    def text(self, x, y, s, scale, colour):
        cx = x
        for ch in s.upper():
            glyph = FONT.get(ch, FONT[" "])
            for row in range(7):
                bits = glyph[row]
                for col in range(5):
                    if bits & (1 << (4 - col)):
                        self.rect(cx + col * scale, y + row * scale,
                                  scale, scale, colour)
            cx += 6 * scale
        return cx

    def text_width(self, s, scale):
        return max(len(s) - 1, 0) * 6 * scale + 5 * scale if s else 0

    def centred(self, y, s, scale, colour):
        x = (self.width - self.text_width(s, scale)) // 2
        self.text(x, y, s, scale, colour)

    def wrapped(self, x, y, s, scale, colour, max_width, leading=None):
        if leading is None:
            leading = 9 * scale
        words = s.split()
        line = ""
        for word in words:
            trial = word if not line else line + " " + word
            if self.text_width(trial, scale) <= max_width:
                line = trial
            else:
                self.text(x, y, line, scale, colour)
                y += leading
                line = word
        if line:
            self.text(x, y, line, scale, colour)
            y += leading
        return y


def draw_chip_chart(cv, x, y, w, h):
    """Lead picture: a chip under a soaring market chart."""
    cv.rect(x, y, w, h, (210, 224, 214))
    # Rising chart lines across the top of the scene.
    pts = [(x + 18, y + 118), (x + 130, y + 96), (x + 240, y + 104),
           (x + 350, y + 62), (x + 470, y + 30)]
    for (ax, ay), (bx, by) in zip(pts, pts[1:]):
        cv.line(ax, ay, bx, by, GREEN, 6)
    for px, py in pts:
        cv.disc(px, py, 7, GREEN)
    cv.line(x + 470, y + 30, x + 448, y + 28, GREEN, 6)
    cv.line(x + 470, y + 30, x + 468, y + 52, GREEN, 6)
    # The chip: a dark square with gold pins on every side.
    cx, cy, s = x + w // 2 - 44, y + h - 92, 88
    cv.rect(cx, cy, s, s, INK)
    cv.rect(cx + 22, cy + 22, s - 44, s - 44, TEAL)
    for i in range(5):
        off = 10 + i * 17
        cv.rect(cx + off, cy - 12, 7, 12, GOLD)
        cv.rect(cx + off, cy + s, 7, 12, GOLD)
        cv.rect(cx - 12, cy + off, 12, 7, GOLD)
        cv.rect(cx + s, cy + off, 12, 7, GOLD)
    cv.text(x + 18, y + h - 28, "+33% NVIDIA", 2, INK)


